export type TextKey = keyof typeof TEXT;

export function t(key: TextKey, vars?: Record<string, string | number>): string {
  const text: string = TEXT[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}

// How a shop sells, in words
export function channelLabel(channel: string): string {
  if (channel === 'online') return t('channel.online');
  if (channel === 'both') return t('channel.both');
  return t('channel.shop');
}
